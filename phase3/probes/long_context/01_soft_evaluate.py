class SoftEvaluation:
    """
    Class to perform soft evaluation of the model.
    Note: To run the methods of this class make sure that the property "multi_tag" in config.json is set to true.
    Args:
        labels_map (dict): A mapping of label index to labels.
        config (dict): A configuration of the model.
        checkpoint_path (str): A checkpoint path.
        model_id (str): ID of the model which will be used to create reports directory.
        model (src.models.nlp.classification_engine.architecture.net.FeedbackClassifier): A FeedbackClassifier model
        to evaluate.
    """

    def __init__(self, labels_map, config, checkpoint_path=None, model_id=None, model=None):
        """
        Initializes the variables.
        Args:
            labels_map (dict): A mapping of label index to labels.
            config (dict): A configuration of the model.
            checkpoint_path (str): A checkpoint path.
            model_id (str): ID of the model which will be used to create reports directory.
            model (src.models.nlp.classification_engine.architecture.net.FeedbackClassifier): A FeedbackClassifier model
            to evaluate.
        """
        self.device = torch.device("cuda") if torch.cuda.is_available() else "cpu"
        self.labels_map = labels_map
        self.config = config
        if checkpoint_path is not None:
            self.checkpoint_id = checkpoint_path.split("/")[-1].split(".")[0]
            checkpoint = torch.load(checkpoint_path, map_location=torch.device(self.device))
            self.model = FeedbackClassifier(self.config).to(self.device)
            self.model.load_state_dict(checkpoint["model_state_dict"])
        else:
            self.checkpoint_id = model_id
            self.model = model
        self.loss_fn = nn.CrossEntropyLoss().to(self.device)
        self.report_dir = common_utils.create_dir(os.path.join(settings.REPORTS_DIR, self.checkpoint_id))
        self.softmax = nn.Softmax(dim=1)

    def calculate_strict_count(self, data_labels, outputs) -> int:
        """
        Counts the number of correct predictions.
        Args:
            data_labels (torch.Tensor): The true labels of the dataset.
            outputs (torch.Tensor of torch.Tensor): The output values from the model.
        Returns:
            The number of correct predictions.
        """
        predictions = torch.argmax(outputs, dim=-1)
        top_data_labels = []
        for data_label in data_labels:
            labels = common_utils.split_int(data_label)
            top_data_labels.append(labels[0])
        return np.count_nonzero((predictions.cpu() == torch.tensor(top_data_labels)))

    def calculate_lenient_count(self, data_labels, outputs) -> int:
        """
        Counts the number of correct predictions. If the model predicts any one of the true label, then the prediction
        will be considered as correct prediction. This method is used especially when there are multiple true labels for
        a single data point.
        Args:
            data_labels (torch.Tensor): The true labels of the dataset.
            outputs (torch.Tensor of torch.Tensor): The output values from the model.
        Returns:
            The number of correct predictions.
        """
        cnt = 0
        for data_label, output in zip(data_labels, outputs):
            labels = common_utils.split_int(data_label)
            prediction = torch.argmax(output)
            if prediction in labels:
                cnt += 1
        return cnt

    def calculate_max_margin_score(self, data_labels, outputs) -> float:
        """
        Calculate the total probabilities of the true labels. This method sums up the probabilities generated by the model
        for each of the true label of the data point. This method is used when there are multiple true labels for a
        single data point.
        Args:
            data_labels (torch.Tensor): The true labels of the dataset.
            outputs (torch.Tensor of torch.Tensor): The output values from the model.
        Returns:
            The sum of probabilities of the true labels.
        """
        prob_sum = 0
        for data_label, output in zip(data_labels, outputs):
            labels = common_utils.split_int(data_label)
            probs = [output[label].item() for label in labels]
            prob_sum += sum(probs)
        return prob_sum

    def calculate_valid_counts(self, data_labels, outputs) -> tuple:
        """
        Calls the individual method to return a tuple of strict, lenient count, and maximum margin score.
        Args:
            data_labels (torch.Tensor): The true labels of the dataset.
            outputs (torch.Tensor of torch.Tensor): The output values from the model.
        Returns:
            A tuple of strict count, lenient count, and maximum margin score.
        """
        strict_count = self.calculate_strict_count(data_labels, outputs)
        lenient_count = self.calculate_lenient_count(data_labels, outputs)
        max_margin_score = self.calculate_max_margin_score(data_labels, outputs)
        return strict_count, lenient_count, max_margin_score

    def calculate_accuracy_score(self, total_strict_count, total_lenient_count, total_max_margin_score,
                                 dataset_len) -> tuple:
        """
        Calculates strict accuracy, lenient accuracy, and maximum margin score, and saves the scores in the
        "test_accuracy.txt" in a directory.
        Args:
            total_strict_count (int): The total strict count.
            total_lenient_count (int): The total lenient count.
            total_max_margin_score (float): The sum of maximum margin score.
            dataset_len (int): The size of the dataset
        Returns:
            A tuple of strict accuracy, lenient accuracy, and maximum margin score.
        """
        # strict accuracy also depends on the order of labels in multilabel
        strict_acc = int(round((100 * total_strict_count / dataset_len), 0))
        lenient_acc = int(round((100 * total_lenient_count / dataset_len), 0))
        max_margin_score = int(round((100 * total_max_margin_score / dataset_len), 0))
        logger.info(f"strict_accuracy: {strict_acc}")
        logger.info(f"lenient_accuracy: {lenient_acc}")
        logger.info(f"max_margin_score: {max_margin_score}")
        common_utils.save_to_txt(self.report_dir, str({"strict_acc": strict_acc, "lenient_acc": lenient_acc,
                                                       "max_margin_score": max_margin_score}), "test_accuracy")
        return strict_acc, lenient_acc, max_margin_score

    def predict(self, loader, calculate_acc=False) -> tuple[list[float], list[int], int, int, int] | tuple[
        list[float], list[int]]:
        """
        Make prediction of the dataset using the model.
        Args:
            loader (torch.utils.data.DataLoader): A dataloader containing dataset.
            calculate_acc (bool): A boolean value to determine whether to calculate accuracies and return them.
        Returns:
            A tuple of list of probabilities for each dataset, list of predictions, strict accuracy, lenient accuracy,
            and maximum margin score. If "calculate_acc" = False, the method does not return the strict accuracy, lenient
            accuracy, and maximum margin score value.
        """

        results_probs, results_predictions = [], []
        total_strict_acc, total_lenient_acc, total_max_margin_score = 0, 0, 0

        with torch.no_grad():
            self.model.eval()
            for data_inputs, data_labels in loader:
                input_ids = data_inputs['input_ids'].squeeze(1).to(self.device)
                attention_masks = data_inputs['attention_mask'].to(self.device)

                outputs = self.model(input_ids, attention_masks)
                output_probs = self.softmax(outputs)
                results_probs.extend([probs.tolist() for probs in output_probs])

                predictions = torch.argmax(outputs, dim=-1)
                results_predictions.extend([prediction.item() for prediction in predictions])

                if calculate_acc:
                    batch_strict_acc, batch_lenient_acc, batch_max_margin_score = self.calculate_valid_counts(
                        data_labels,
                        output_probs)
                    total_strict_acc += batch_strict_acc
                    total_lenient_acc += batch_lenient_acc
                    total_max_margin_score += batch_max_margin_score

        if calculate_acc:
            strict_acc, lenient_acc, max_margin_score = self.calculate_accuracy_score(total_strict_acc,
                                                                                      total_lenient_acc,
                                                                                      total_max_margin_score,
                                                                                      len(loader.dataset))
            return results_probs, results_predictions, strict_acc, lenient_acc, max_margin_score
        return results_probs, results_predictions

    def _format_output(self, probs_float_lst, round_val=2, all_prob=False) -> str:
        """
        Formats the probability distribution output.
        Args:
            probs_float_lst (list of float): The list of probability values.
        Returns:
            A string containing the list of probabilities separated by comma.
        """
        # enumerate the probabilities to get the label index
        probs_lst = list(enumerate(probs_float_lst))

        # sort the probabilities
        probs_lst.sort(key=lambda x: x[1], reverse=True)

        if all_prob:
            sorted_probs_lst = [str((self.labels_map[label], str(round(prob, round_val)).lstrip("0"))) for label, prob
                                in probs_lst]

        else:
            # map the index value to label value, remove the preceding 0 from the probability i.e. 0.5643 becomes .56
            sorted_probs_lst = [str((self.labels_map[label], str(round(prob, round_val)).lstrip("0"))) for label, prob
                                in probs_lst if round(prob, 2) != 0]

        return ", ".join(sorted_probs_lst).replace("'", "")

    def _remove_single_quote(self, multilabel_str) -> str:
        """
        Removes single quote present in each label.
        Args:
            multilabel_str (str): A string containing multiple labels.
        Returns:
            A string containing multiple labels separated by comma.
        """
        multilabel = multilabel_str.split(",")
        return ",".join(multilabel).replace("'", "")

    def format_output_df(self, df, round_val=2, all_prob=False) -> pd.DataFrame:
        """
        Formats the DataFrame to output.
        Args:
            df (pd.DataFrame): A DataFrame.
            round_val:
            all_prob:
        Returns:
            pd.DataFrame: A DataFrame consisting of the following columns:
                - submission_id: The submission_id of the feedback.
                - feedback: A feedback text.
                - multilabel: A string containing multiple labels separated by comma.
                - output: The formatted output probabilities. e.g. (ADS, .56), (1ART, .41)
        """
        in_df = df.copy()
        in_df["multilabel"] = in_df["multilabel"].apply(lambda x: self._remove_single_quote(x))
        in_df["output"] = in_df["output"].apply(lambda x: self._format_output(x, round_val, all_prob))
        return in_df[["submission_id", "feedback", "multilabel", "output"]]

    def init_predict(self):
        """
        Make predictions on the test dataset and save the formatted output in the CSV file "test_multilabel_output.csv"
        in the directory.
        """
        test_dataset = FeedbackDataset(settings.TEST_FILE_PATH, self.labels_map, self.config)
        test_dataloader = DataLoader(test_dataset, batch_size=self.config["bs"], shuffle=False)
        test_df = test_dataset.get_df()
        results_probs, _ = self.predict(test_dataloader)
        test_df["output"] = results_probs
        formatted_test_df = self.format_output_df(test_df)
        formatted_test_df.sort_values(by="multilabel", inplace=True)
        common_utils.save_dataframes(self.report_dir, [formatted_test_df], ["test_multilabel_output"])

    def init_predict_all_prob(self):
        test_dataset = FeedbackDataset(settings.TEST_FILE_PATH, self.labels_map, self.config)
        test_dataloader = DataLoader(test_dataset, batch_size=self.config["bs"], shuffle=False)
        test_df = test_dataset.get_df()
        results_probs, _ = self.predict(test_dataloader)
        test_df["output"] = results_probs

        formatted_test_df = self.format_output_df(test_df, round_val=4, all_prob=True)
        formatted_test_df.sort_values(by="multilabel", inplace=True)

        common_utils.save_dataframes(self.report_dir, [formatted_test_df], ["test_output_all_prob"])

    def get_test_accuracy(self) -> tuple:
        """
        Generates the test accuracies.
        Returns:
            The actual accuracy, strict accuracy, lenient accuracy, and maximum margin score of the test dataset.
        """
        test_dataset = FeedbackDataset(settings.TEST_FILE_PATH, self.labels_map, self.config)
        test_dataloader = DataLoader(test_dataset, batch_size=self.config["bs"], shuffle=False)
        test_df = test_dataset.get_df()
        results_probs, results_predictions, strict_acc, lenient_acc, max_margin_score = self.predict(test_dataloader,
                                                                                                     calculate_acc=True)
        test_df["predicted_target"] = results_predictions
        accuracy = accuracy_score(test_df["target"].values.tolist(), test_df["predicted_target"].values.tolist()) * 100
        return int(round(accuracy, 0)), strict_acc, lenient_acc, max_margin_score


    def create_confusion_matrix(self, soft_prediction=True):
        """
        Creates confusion matrix of the test dataset.
        Args:
            soft_prediction (bool): A boolean value to determine whether to compute confusion matrix for soft prediction.
        """
        test_dataset = FeedbackDataset(settings.TEST_FILE_PATH, self.labels_map, self.config)
        test_dataloader = DataLoader(test_dataset, batch_size=self.config["bs"], shuffle=False)
        test_df = test_dataset.get_df()
        _, results_predictions = self.predict(test_dataloader)
        test_df["predicted_target"] = results_predictions
        if not soft_prediction:
            test_df["multitarget"] = test_df["multitarget"].apply(lambda x: x[0])
        else:
            test_df["multitarget"] = test_df.apply(lambda x: self._get_multi_target(x), axis=1)

        c_matrix_df = classification_utils.calculate_confusion_matrix(test_df["multitarget"].values.tolist(),
                                                                      test_df["predicted_target"].values.tolist(),
                                                                      self.labels_map)
        c_matrix_per_df = classification_utils.calculate_confusion_matrix_percent(list(self.labels_map.values()),
                                                                                  c_matrix_df)
        common_utils.save_dataframes(self.report_dir, [c_matrix_per_df], ["test_soft_confusion_matrix_percent"])

    def _get_multi_target(self, x) -> int:
        """
        Get the value of the target if the multiple target values are present. This method returns the first target value.
        Args:
            x (pd.Series): A row of pd.DataFrame.
        Returns:
            An integer value of the label.
        """
        predicted_target = x["predicted_target"]
        multitarget = x["multitarget"]
        if predicted_target in multitarget:
            return predicted_target
        return multitarget[0]

